#: Решение реализации №7: весовое окно по азимуту при построении картинки.
#: По умолчанию НЕТ — в книге взвешивания нет ни слова, (5-3) это чистая
#: сумма без весов, и реализовано как написано.
#:
#: Но у невзвешенной апертуры первый боковой лепесток равен -13,3 дБ, и это
#: не дефект, а её точное свойство. Для съёмки, где рядом с яркой целью
#: стоит слабая, такие боковики закрывают слабую. Обычный размен в РСА —
#: окно: боковики вниз ценой расширения главного лепестка.
#:
#: Замер на наших данных (validate.experiment_azimuth_window):
#:
#:   окно            первый боковой   ширина по -3 дБ
#:   нет (по книге)      -13,3 дБ         0,94 отсчёта
#:   Хэннинг             -31,5            1,50
#:   Хэмминг             -42,7            1,38
#:   Кайзер beta=6       -43,9            1,50
#:
#: Ставить окно можно ТОЛЬКО здесь, в этапе D, и вот почему. Вывод (5-13) и
#: (5-19) сделан для суммы БЕЗ весов; занеся вес внутрь цикла итераций, мы
#: поменяли бы целевую функцию, и обе производные пришлось бы выводить
#: заново. Взвешивание — вопрос отображения, а не оценки фазы.
AZIMUTH_WINDOWS = ("none", "hann", "hamming", "kaiser6")
AZIMUTH_WINDOW = "none"


def image_shift(backend: Backend, phi_hat) -> int:
    """Сдвиг по азимуту, который найденная фаза даёт изображению блока,
    в отсчётах.

    Принимает бэкенд и вектор phi_hat; возвращает целое число отсчётов,
    положительное — картинка уехала в сторону больших m.

    Откуда это берётся. Подставим phi в (5-3) и вынесем множитель:

        g_phi(m) = sum_k h(k) e^{j phi_k} e^{-j 2 pi k m / M}
                 = ( g_0 * F )(m),   F(m) = sum_k e^{j phi_k} e^{-j 2 pi k m / M}

    то есть изображение с поправкой есть изображение при phi = 0, свёрнутое
    с F — а F это (5-3) от одной лишь комплексной экспоненты, отклик блока
    на точечную цель. Где у F пик, туда вся картинка и переехала.

    Опорная картинка для этого НЕ НУЖНА: F считается из одной только phi.
    Поэтому способ работает и там, где на сцене нет ни одной точечной цели
    и цепляться взаимной корреляции не за что.

    Стоит одно БПФ длины M на блок, вне цикла итераций: §10.6 не задевает.
    """
    phi = backend.to_numpy(phi_hat).astype(np.float64)
    F = np.abs(np.fft.fft(np.exp(1j * phi)))
    M = F.size
    s = int(np.argmax(F))
    return s - M if s > M // 2 else s


def remove_image_shift(backend: Backend, phi_hat) -> np.ndarray:
    """РЕШЕНИЕ РЕАЛИЗАЦИИ №5: снять с phi_hat линейную часть, чтобы блок
    встал на своё место на сцене.

    Принимает бэкенд и найденный phi_hat; возвращает вектор той же длины.

    Зачем. Энтропия (5-5) слепа к линейной по k фазе: та лишь СДВИГАЕТ
    картинку, не меняя ни одного |g|. Значит алгоритм линейную часть не
    определяет и определить не может, и каждый блок приходит со своим
    произвольным сдвигом. Пока блок смотрят по отдельности, это безразлично.
    Но (5-26) укладывает блоки в общую мозаику, и там разнобой сдвигов — это
    разъехавшаяся карта: замерено от -7 до +6 отсчёта между блоками одной
    сцены, то есть свыше 5 метров при r_a = 0,4 м.

    В книге такого шага НЕТ: §6 говорит только «блоки укладываются на свои
    места». Решение принято здесь и замерено (validate.experiment_image_shift).

    Сдвиг берётся ЦЕЛЫЙ, и это существенно: к целому сдвигу энтропия слепа
    точно (замер: разница по (5-6) от 0 до 3e-15), а к дробному — лишь
    приблизительно. Поправка обязана быть бесплатной, иначе она меняла бы
    то, что алгоритм минимизирует.

    Способ НЕ идеален и не выдаётся за идеальный. На 114 блоках с точечными
    целями (5 сцен x 3 вида ошибки): на своём месте было 24,6 %, стало
    48,2 %; средний сдвиг 2,61 -> 0,57 отсчёта, худший 9 -> 2. У 15 блоков
    из 114 стало хуже, чем было.
    """
    phi = backend.to_numpy(phi_hat).astype(np.float64)
    M = phi.size
    k = np.fft.fftfreq(M) * M  # тот же центрированный номер бина
    return phi - 2.0 * np.pi * k * image_shift(backend, phi) / M


def azimuth_window(backend: Backend, h_block, name: str | None = None):
    """РЕШЕНИЕ РЕАЛИЗАЦИИ №7: домножить данные блока на весовое окно по
    азимуту перед (5-3).

    Принимает бэкенд, данные блока h_qk(k,n) и имя окна; возвращает
    взвешенные данные того же размера. Имя 'none' возвращает вход как есть.

    Окно накладывается на ДОПЛЕРОВСКУЮ ось, то есть на ту самую k, по
    которой идёт сумма (5-3). Оно центрируется на нулевой частоте: массив
    лежит в раскладке numpy.fft (сначала положительные частоты, потом
    отрицательные), поэтому окно строится центрированным и переносится
    ifftshift.

    В цикл итераций это НЕ входит и входить не должно: см. AZIMUTH_WINDOW.
    """
    name = AZIMUTH_WINDOW if name is None else name
    # Значение по умолчанию берётся ЗДЕСЬ, а не в подписи функции: в подписи
    # оно связалось бы раз и навсегда при определении, и смена AZIMUTH_WINDOW
    # на ходу не подействовала бы. Ровно на эти грабли уже наступали.
    if name == "none":
        return h_block
    if name not in AZIMUTH_WINDOWS:
        raise ValueError(f"неизвестное окно {name!r}; есть {AZIMUTH_WINDOWS}")

    M = h_block.shape[0]
    if name == "hann":
        w = np.hanning(M + 1)[:M]
    elif name == "hamming":
        w = np.hamming(M + 1)[:M]
    else:  # kaiser6
        w = np.kaiser(M + 1, 6.0)[:M]
    w = np.fft.ifftshift(w)  # центр окна -> нулевая частота
    return h_block * backend.asarray(w)[:, None]


def block_image(backend: Backend, h_block, phi_hat):
    """(5-3) с найденным phi_hat: финальное изображение блока.

        g_qk(m,n) = sum_k h_qk(k,n) e^{j phi_hat_k} e^{-j 2 pi k m / M}

    Принимает бэкенд, данные блока h_qk(k,n) и сошедшийся вектор phi_hat
    длины M; возвращает комплексное изображение блока (M, N). M, N здесь —
    размеры БЛОКА, как объявлено в §5 документа, а не сцены.

    Это ровно то же (5-3), что и на шаге 2 итерации, но вне цикла: в
    стоимость итерации (§10.6) оно не входит.
    """
    h_block = backend.asarray(h_block)
    phi = backend.asarray(phi_hat)  # хоть numpy, хоть уже на устройстве
    return backend.fft_kernel_minus(h_block * backend.xp.exp(1j * phi)[:, None])


def assemble(backend: Backend, images: dict[int, object], blocks: list[Block], M: int, N: int):
    """Укладка блоков на свои места в сцене согласно нумерации (5-26).

    Принимает бэкенд, словарь {q_k: изображение блока}, список блоков этапа A
    и размеры сцены; возвращает собранное изображение (M, N).

    Блоки нарезаны из ИЗОБРАЖЕНИЯ сцены плитками m_p x n_p (см. block_grid), и
    сборка — это обратная укладка тех же плиток. Каждая плитка встаёт по
    своим (m_start:m_stop, n_start:n_stop), то есть ровно туда, откуда была
    взята, а её сквозной номер q_k = m_k + M_k(n_k - 1) — это (5-26).

    Размер изображения блока совпадает с его местом на сцене отсчёт в отсчёт:
    (5-3) взято длиной в блок, значит и выдаёт ровно m_b строк. Подрезать или
    дополнять нечего.
    """
    out = backend.xp.zeros((M, N), dtype=backend.complex_dtype)
    for block in blocks:
        out[block.m_start : block.m_stop, block.n_start : block.n_stop] = images[block.q_k]
    return out
