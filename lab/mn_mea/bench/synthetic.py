from dataclasses import dataclass, field

import numpy as np

from backend import Backend

#: Виды сцены, §7.4 задания.
SCENES = ("points", "points_and_clutter", "clutter_only")

#: Виды вносимой ошибки фазы, §7.3 задания.
ERROR_KINDS = ("quadratic", "cubic", "jitter", "mixture")

#: Дрожание (§7.3) — это неучтённое ОТКЛОНЕНИЕ НОСИТЕЛЯ, а оно плавное:
#: несколько периодов на апертуру, а не белый шум от бина к бину. Диапазон
#: гармоник выбран так, чтобы отклонение было заведомо не описываемо
#: квадратичной моделью этапа B (её период на апертуре — один), но и не
#: вырождалось в шум, к которому никакой автофокус не применим.
JITTER_HARMONICS = (2, 3, 4, 5)

#: Доля частоты повторения, занятая обработанной доплеровской полосой.
#: Не украшение, а физика: диаграмма направленности антенны ограничивает
#: азимутальный спектр полосой B_a, и она ВСЕГДА уже PRF — иначе спектр
#: сворачивался бы сам на себя. Отсюда изображение по азимуту получается
#: передискретизованным, а отклик точечной цели — синком шириной в
#: несколько отсчётов, а не в один.
#:
#: Пока этой доли не было (то есть она равнялась единице), отклик цели
#: занимал РОВНО один отсчёт: синк был, но опрашивался в своих нулях, и
#: ширина по -3 дБ упиралась в 1,00 при любой фокусировке. Мера была
#: бесполезна, а картинка — непохожа на радиолокационную.
#:
#: ПОКА ВЫКЛЮЧЕНО (1,0 — полоса во всю PRF, ограничения нет), и вот почему.
#: При 0,8 пятая часть доплеровских бинов оказывается строго нулевой. Там
#: |h| = 0, значит (5-19) даёт E'' = 0, сторож решения №2 их замораживает, и
#: фаза в них остаётся неопределённой — что физически ВЕРНО: где нет сигнала,
#: там нечего и оценивать. Но мера остатка (validate.phase_residual_rms)
#: сравнивает ВСЕ бины и записывает неопределённые в ошибку: остаток этапа C
#: подскакивает с 0,046 до 0,93 рад, и приёмка §10 падает.
#:
#: То есть включать полосу надо вместе с исправлением меры — считать остаток
#: только по занятым бинам. Это отдельная работа, и делать её наспех, оставив
#: прогон красным, нельзя. Функция и разбор оставлены на месте: поставьте 0,8,
#: и полоса заработает.
#:
#: Для РСА обычное отношение обработанной полосы к PRF — около 0,8.
AZIMUTH_BANDWIDTH_FRACTION = 1.0

#: Яркость точечной цели относительно среднеквадратичного уровня фона
#: в сцене 'points_and_clutter'. Не выдумано: выбрано так, чтобы отклик
#: точки был на 40 дБ над фоном — обычный для РСА рабочий контраст, и
#: при этом порог решения №1 (-120 дБ) заведомо не срабатывает.
POINT_TO_CLUTTER_DB = 40.0


@dataclass
class Scene:
    """Истинное изображение и координаты внесённых точечных целей.

    Координаты нужны, чтобы замерить выигрыш по пику и ширину отклика по
    азимуту (§8 задания) именно там, куда точка была положена, а не там,
    где её потом кто-то нашёл."""

    image: np.ndarray
    kind: str
    points: list[tuple[int, int]] = field(default_factory=list)
    #: Дробное смещение каждой цели по азимуту относительно центра своего
    #: отсчёта, в отсчётах, в диапазоне [-0.5, 0.5). Нужно для §8 задания:
    #: ширина отклика меряется относительно ИСТИННОГО положения цели.
    point_offsets: list[float] = field(default_factory=list)


def scene(kind: str, M: int, N: int, rng: np.random.Generator, n_points: int = 6) -> Scene:
    """Истинное сфокусированное изображение g_true — §7.4 задания.

    Принимает вид сцены, размеры (M, N) и генератор; возвращает Scene —
    комплексный массив (M, N) и список координат точечных целей.

      'points'              одиночные точечные цели: есть чему фокусироваться,
                            результат очевиден. Содержит ТОЧНЫЕ нули — именно
                            на этой сцене работает решение реализации №1.
      'points_and_clutter'  точки плюс распределённый фон: ближе к жизни.
      'clutter_only'        только фон, ни одной точки. ОБЯЗАТЕЛЬНАЯ сцена:
                            энтропийный критерий на однородном спекле может
                            не иметь выраженного минимума.

    Фон — полностью развитый спекл: комплексное гауссово поле, у которого
    |g|^2 распределено экспоненциально.

    ТОЧКА СТАВИТСЯ НЕ В ЦЕНТР ОТСЧЁТА. Раньше цель была одной ячейкой,
    g[m,n] = A, и это неверно: дельта в изображении отвечает цели, стоящей
    РОВНО в центре пикселя, и отклик у неё шириной в один отсчёт, без
    боковых лепестков. В жизни так не бывает. Теперь у каждой цели есть
    дробное смещение в [-0.5, 0.5), а её отклик — ядро Дирихле (периодический
    синк), то есть то, что и даёт прямоугольная апертура: первый боковой
    лепесток -13 дБ, спад по 1/x, и потери на расстройку до -3,9 дБ, когда
    цель попадает ровно между отсчётами.

    Строится отклик точно — через (5-3) от одной комплексной экспоненты, а
    не приближённой формулой синка.

    По ДАЛЬНОСТИ цель по-прежнему ставится в свой строб целиком: этап C
    работает только по азимуту, стробы дальности для него независимы.
    """
    if kind not in SCENES:
        raise ValueError(f"неизвестная сцена {kind!r}; есть {SCENES}")

    g = np.zeros((M, N), dtype=np.complex128)
    points: list[tuple[int, int]] = []
    offsets: list[float] = []

    if kind in ("points", "points_and_clutter"):
        amplitude = 1.0 if kind == "points" else 10.0 ** (POINT_TO_CLUTTER_DB / 20.0)
        rows = rng.choice(M, size=n_points, replace=n_points > M)
        cols = rng.choice(N, size=n_points, replace=n_points > N)
        k = np.arange(M)
        for m, n in zip(rows, cols):
            shift = rng.uniform(-0.5, 0.5)  # цель не в центре отсчёта, см. ниже
            m_true = m + shift
            # Отклик полной апертуры на точку в m_true: ядро Дирихле, оно же
            # периодический синк. Строится точно, через (5-3) от одной
            # комплексной экспоненты, а не приближённой формулой.
            response = np.fft.fft(np.exp(2j * np.pi * k * m_true / M)) / M
            g[:, n] += amplitude * np.exp(2j * np.pi * rng.random()) * response
            points.append((int(m), int(n)))
            offsets.append(float(shift))

    if kind in ("points_and_clutter", "clutter_only"):
        g += (rng.normal(size=(M, N)) + 1j * rng.normal(size=(M, N))) / np.sqrt(2.0)

    return Scene(image=azimuth_band_limit(g), kind=kind, points=points,
                 point_offsets=offsets)


def azimuth_band_limit(g: np.ndarray, fraction: float = AZIMUTH_BANDWIDTH_FRACTION):
    """Ограничить азимутальный спектр изображения полосой fraction * PRF.

    Принимает изображение (M, N) и долю полосы; возвращает изображение того
    же размера.

    Это диаграмма направленности антенны, а не фильтр по вкусу: она задаёт
    доплеровскую полосу B_a, и та всегда уже частоты повторения. Бины за
    полосой сигнала не несут, и в h(k,n) они нулевые.

    Следствий два, и оба нужны стенду. Изображение по азимуту становится
    ПЕРЕДИСКРЕТИЗОВАННЫМ, и отклик точечной цели виден как синк шириной в
    несколько отсчётов — ширину по -3 дБ становится осмысленно мерить. И у
    бинов за полосой |h| = 0, значит (5-19) даёт там E'' = 0: сторож решения
    №2 получает настоящий повод сработать, а не только на синтетических
    нулях.

    Окно прямоугольное — классический необработанный случай с первым
    боковым лепестком -13,3 дБ. Взвешивание (Хэмминг и прочее) в книге не
    упоминается и здесь не вводится.
    """
    if fraction >= 1.0:
        return g
    M = g.shape[0]
    keep = int(round(fraction * M))
    spectrum = np.fft.ifft(g, axis=0)
    mask = np.zeros(M, dtype=bool)
    half = keep // 2
    mask[: half + keep % 2] = True   # положительные частоты
    mask[M - half:] = True           # отрицательные
    spectrum[~mask] = 0.0
    return np.fft.fft(spectrum, axis=0)


def phase_error(
    kind: str, M: int, edge_rad: float, rng: np.random.Generator, T_a: float = 1.0
) -> np.ndarray:
    """Вносимая ошибка фазы phi_err — §7.3 задания. Это ИСТИНА опыта.

    Принимает вид ошибки, длину M, размах на краю апертуры в радианах,
    генератор и время синтеза; возвращает вектор длины M.

      'quadratic'  квадратичная по f_a — расфокусировка, то, что этап B
                   и описывает
      'cubic'      кубическая — остаточная асимметрия
      'jitter'     дрожание — неучтённое отклонение носителя: плавная
                   случайная добавка из гармоник JITTER_HARMONICS
      'mixture'    смесь — живой случай

    Размах задаётся значением на краю апертуры (|f_a| максимально), потому
    что именно край определяет расфокусировку. Для дрожания размах — это
    среднеквадратичное значение по апертуре.
    """
    if kind not in ERROR_KINDS:
        raise ValueError(f"неизвестный вид ошибки {kind!r}; есть {ERROR_KINDS}")

    f_a = np.fft.fftfreq(M, d=T_a / M)
    u = f_a / np.abs(f_a).max()  # нормированная частота, край = +-1

    if kind == "quadratic":
        return edge_rad * u**2
    if kind == "cubic":
        return edge_rad * u**3
    if kind == "jitter":
        return edge_rad * _smooth_deviation(u, rng)
    # 'mixture': квадратичная основа, кубическая асимметрия и дрожание
    return edge_rad * (0.6 * u**2 + 0.3 * u**3 + 0.3 * _smooth_deviation(u, rng))


def _smooth_deviation(u: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    """Плавное отклонение носителя единичного СКО: сумма гармоник
    JITTER_HARMONICS по апертуре со случайными амплитудами и фазами.

    Принимает нормированную частоту u (край апертуры = +-1) и генератор;
    возвращает вектор той же длины со среднеквадратичным значением 1.
    """
    deviation = np.zeros_like(u)
    for harmonic in JITTER_HARMONICS:
        deviation += rng.normal() * np.sin(np.pi * harmonic * (u + 1.0) / 2.0 + 2 * np.pi * rng.random())
    return deviation / deviation.std()


def variance_scale(D_x: float, D_y: float, x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Множитель изменчивости s = D_x x + D_y y из (5-27), в точке местности.

    Принимает D_x, D_y этапа B и координаты относительно центра сцены в
    метрах; возвращает скаляр или массив той же формы.

    Вся пространственная изменчивость квадратичной фазы книги входит через
    это одно число: (5-27) есть s * f_a^2. Поэтому и вносить её достаточно
    так же — иначе стенд проверял бы не ту модель, которую реализует этап B.
    """
    return D_x * np.asarray(x) + D_y * np.asarray(y)


def spatially_variant_truth(s: float, f_a: np.ndarray) -> np.ndarray:
    """(5-27) как ИСТИНА стенда: eps = s * f_a^2 для точки местности с
    множителем s = variance_scale(...).

    Принимает множитель s и ось азимутальных частот; возвращает вектор фазы
    той же длины, что и f_a.

    Это ровно та функция, которую этап B пытается угадать через eta * eps
    (5-29)/(5-30). Совпадение модели намеренное: если стенд вносит одно, а
    этап B описывает другое, то замер скажет не о качестве этапа B, а о
    разнице двух моделей.
    """
    return s * np.asarray(f_a) ** 2


def range_doppler_spatially_variant(
    backend: Backend,
    g_true: np.ndarray,
    f_a: np.ndarray,
    s_map: np.ndarray,
    phi_common: np.ndarray | None = None,
) -> np.ndarray:
    """Данные h(k,n) с ПРОСТРАНСТВЕННО ИЗМЕНЧИВОЙ ошибкой фазы.

    Принимает бэкенд, истинное изображение g_true (M, N), ось частот f_a
    длины M, карту множителей s_map (M, N) по (5-27) и необязательную общую
    для всей сцены добавку phi_common длины M; возвращает h(k,n) (M, N).

        h(k,n) = (1/M) sum_m g_true(m,n) e^{+j 2 pi k m / M}
                                          e^{-j[ s(m,n) f_a(k)^2 + phi_common(k) ]}

    Ядро со знаком ПЛЮС и множитель 1/M — потому что это обращение (5-3), у
    которой ядро с минусом; при s = 0 сумма обязана совпасть с
    range_doppler_from_scene отсчёт в отсчёт, и это проверяется замером.

    Почему нельзя проще. Неизменчивую ошибку вносят одним умножением
    h * e^{-j phi}, потому что она одна на все m. Изменчивая своя у каждого
    пикселя азимута, а m и k — сопряжённые переменные: домножением в области
    k такого не сделать. Поэтому сумма берётся честно, отсчёт за отсчётом:
    каждый рассеиватель вносится со своей поправкой.

    Стоит это M x M на строб дальности — заметно дороже одного БПФ, но это
    стенд, а не алгоритм, и считается один раз на прогон.
    """
    g = backend.to_numpy(g_true)
    M, N = g.shape
    f_a = np.asarray(f_a, dtype=np.float64)
    s_map = np.asarray(s_map, dtype=np.float64)
    common = np.zeros(M) if phi_common is None else np.asarray(phi_common, dtype=np.float64)

    k = np.arange(M)
    kernel = np.exp(2j * np.pi * np.outer(k, np.arange(M)) / M)  # обращение (5-3)
    f2 = (f_a ** 2)[:, None]                                      # (M, 1) по k
    out = np.empty((M, N), dtype=np.complex128)
    for n in range(N):
        # e^{-j s(m,n) f_a(k)^2}: своя поправка каждому азимутальному отсчёту
        phase = np.exp(-1j * f2 * s_map[:, n][None, :])
        out[:, n] = (kernel * phase) @ g[:, n]
    out *= np.exp(-1j * common)[:, None]
    return backend.asarray(out / (backend.alpha * M))


def range_doppler_from_scene(
    backend: Backend, g_true: np.ndarray, phi_err: np.ndarray
) -> np.ndarray:
    """Данные h(k,n) в области дальность-доплер с внесённой ошибкой фазы.

    Принимает бэкенд, истинное изображение g_true (M, N) и истинную ошибку
    phi_err длины M; возвращает комплексный массив h(k,n) размера (M, N).

    Обращение (5-3): ядро (5-3) — это прямое ПФ с множителем alpha, поэтому
    обратное к нему несёт множитель 1/(alpha M). Ошибка вносится множителем
    e^{-j phi_err}, чтобы (5-3) при phi = phi_err вернуло ровно g_true.

    Массив h ФИКСИРОВАН на всё время работы алгоритма и не пересчитывается
    (§2 документа).
    """
    g = backend.asarray(g_true)
    h_ideal = backend.xp.fft.ifft(g, axis=0) / backend.alpha
    return h_ideal * backend.xp.exp(-1j * backend.asarray(phi_err))[:, None]
