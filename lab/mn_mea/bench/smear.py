"""Линейка размаза: во сколько раз отклик цели шире, чем должен быть.

Нужна потому, что «размаз как был, так и остался» — суждение глазом, а
спорить об изображении глазами нельзя. Здесь то же самое числом, и числа
подобраны так, чтобы отвечать именно тому, что глаз и видит.

Что меряется у каждой яркой цели:

    ширина по -3 дБ     главный лепесток. Для сфокусированной цели равна
                        0,886 элемента разрешения — это свойство синка, а
                        не подгонка
    ширина по -10 дБ    и по -20 дБ: сюда попадают хвосты, и ИМЕННО их
                        видно глазом как размаз. Главный лепесток шириной
                        в 7 отсчётов на графике занимает 0,7 пикселя и
                        невидим, а хвост в 300 отсчётов виден отлично
    ISLR                доля энергии ВНЕ главного лепестка, в децибелах.
                        Одно число вместо трёх ширин: у сфокусированной
                        цели с прямоугольным окном около -10 дБ, у
                        расфокусированной уходит к нулю и выше

Порядок функций — порядок выполнения:

    find_targets        найти яркие одиночные цели
    azimuth_cut         вырезать КОМПЛЕКСНЫЙ срез по азимуту вокруг цели
    range_cut           то же по ДАЛЬНОСТИ — чтобы отличить размаз от объекта
    upsample            уплотнить срез (validate.interpolated_cut) и взять модуль
    width_at            ширина на заданном уровне, в элементах разрешения
    islr                доля энергии вне главного лепестка
    measure_target      все числа по одной цели
    measure             таблица по картинке
    compare             та же таблица для двух картинок, до и после
    smear_map           КАРТА размаза по всей картинке, плиткой
"""

from __future__ import annotations

import numpy as np

from validate import interpolated_cut

#: Во сколько раз уплотняется срез перед замером. Отклик занимает около
#: семи отсчётов, и мерить по ним ширину на уровне -3 дБ значит округлять
#: до 14 %. Шестнадцатикратное уплотнение доводит шаг до 0,06 отсчёта.
#:
#: Уплотнение делает validate.interpolated_cut — точное восстановление
#: через (5-3), с ЦЕНТРИРОВАННЫМ номером бина. Своё писать не надо, и
#: первая попытка это подтвердила: я дописал нули в конец спектра и брал
#: модуль ДО уплотнения. Оба шага неверны — модуль не ограничен по полосе,
#: а нули в конце объявляют частоты бинов натуральными. Линейка показывала
#: ширину 0,076 элемента вместо теоретических 0,886 и не реагировала на
#: расфокусировку вовсе.
OVERSAMPLE = 16

#: Полуширина окна замера, в элементах разрешения. Хвост, который видно
#: глазом, тянется на десятки элементов; за 24 он уже теряется в фоне.
WINDOW_CELLS = 24.0

#: Полуширина главного лепестка при счёте ISLR, в элементах разрешения.
#: Первый ноль синка стоит ровно на одном элементе разрешения от пика.
MAINLOBE_CELLS = 1.0

#: Насколько цели должны быть разнесены, чтобы считаться одиночными:
#: по азимуту в элементах разрешения, по дальности в стробах.
GUARD_CELLS = 8.0
GUARD_GATES = 4

#: Сколько плиток по азимуту и по дальности в карте размаза. Плитка должна
#: быть шире двух окон замера по азимуту, иначе отклик не помещается; при
#: 6684 отсчётах и окне 168 это даёт потолок около двадцати плиток.
MAP_TILES_M, MAP_TILES_N = 16, 8

#: Во сколько раз самый яркий пиксель плитки должен превышать её медиану,
#: чтобы считать его целью, а не выбросом спекла. У экспоненциально
#: распределённой интенсивности отношение максимума из десятков тысяч
#: отсчётов к медиане само по себе доходит до 15 дБ; 20 дБ — заведомо выше
#: этого, и такой пик уже не случайность.
MAP_PEAK_OVER_MEDIAN_DB = 20.0

#: На сколько децибел пик СРЕЗА должен превышать медиану ЭТОГО ЖЕ СРЕЗА,
#: чтобы ширину по -20 дБ вообще можно было измерить.
#:
#: Это не украшение, а исправление настоящей ошибки. Медиана плитки —
#: негодный отсчёт: плитка бывает наполовину водой, наполовину лесом, её
#: медиана низка, и яркий спекл леса проходит порог, не будучи целью.
#: Ширина отклика у спекла — случайное число, и карта показывала его как
#: размаз. Поверка вскрыла это сразу: на ИДЕАЛЬНО сфокусированной картинке
#: карта давала отношение 34,4 и ширину 47,9 элемента вместо 1 и 1,8, а с
#: ростом внесённой ошибки числа скакали без порядка: 34,4 -> 4,5 -> 20,6.
#:
#: Правильный отсчёт — медиана самого среза: если пик не выше её на 20 дБ,
#: то уровень -20 дБ лежит ВНУТРИ фона, и пересечение с ним не имеет
#: отношения к отклику цели.
CUT_DYNAMIC_DB = 20.0


def find_targets(image: np.ndarray, cells: float, count: int,
                 window: int) -> list[tuple[int, int]]:
    """Найти яркие одиночные цели.

    Принимает картинку (M, N), ширину элемента разрешения в отсчётах, число
    целей и полуширину окна замера; возвращает список (m, n).

    Жадно: берётся самый яркий пиксель, вокруг него всё гасится, берётся
    следующий. Гашение и есть условие одиночности — две цели ближе GUARD
    считаются одной, и мерить у них ширину бессмысленно.

    Цели у самого края по азимуту пропускаются: окно замера должно целиком
    лежать в картинке, иначе ширина занизится обрезанием хвоста.
    """
    power = np.abs(np.asarray(image)) ** 2
    M, N = power.shape
    guard_m = max(int(round(GUARD_CELLS * cells)), 1)
    found: list[tuple[int, int]] = []

    work = power.copy()
    work[:window, :] = 0.0
    work[M - window:, :] = 0.0
    for _ in range(count):
        if not work.any():
            break
        m, n = np.unravel_index(int(np.argmax(work)), work.shape)
        found.append((int(m), int(n)))
        lo_m, hi_m = max(m - guard_m, 0), min(m + guard_m + 1, M)
        lo_n, hi_n = max(n - GUARD_GATES, 0), min(n + GUARD_GATES + 1, N)
        work[lo_m:hi_m, lo_n:hi_n] = 0.0
    return found


def azimuth_cut(image: np.ndarray, m: int, n: int, window: int) -> np.ndarray:
    """КОМПЛЕКСНЫЙ срез по азимуту вокруг цели, длиной 2*window.

    Комплексный, а не модуль: уплотнять надо сигнал, а не его модуль. У
    модуля спектр не ограничен, и дополнение нулями для него — уже не
    точное восстановление, а выдумка.
    """
    return np.asarray(image)[m - window : m + window, n]


def range_cut(image: np.ndarray, m: int, n: int, window: int) -> np.ndarray:
    """КОМПЛЕКСНЫЙ срез по ДАЛЬНОСТИ вокруг цели.

    Принимает картинку, координаты цели и полуширину окна; возвращает срез.

    Зачем он нужен. Автофокус правит фазу ТОЛЬКО по азимуту, по дальности
    он не трогает ничего. Значит если цель широка и по дальности тоже —
    это не расфокусировка, а либо протяжённый объект (угол здания, техника,
    кромка берега), либо остаточная миграция дальности, и азимутальным
    автофокусом её не лечат.

    Окно берётся то же, что по азимуту, но в стробах: сколько стробов
    занимает элемент разрешения по дальности, скрипту неизвестно — r_b в
    Geometry одно число, — поэтому ширина возвращается в ОТСЧЁТАХ, а не в
    элементах разрешения.
    """
    row = np.asarray(image)[m, :]
    lo, hi = max(n - window, 0), min(n + window, row.size)
    return row[lo:hi]


def upsample(cut: np.ndarray, factor: int = OVERSAMPLE) -> np.ndarray:
    """Уплотнить срез и вернуть модуль.

    Принимает комплексный срез и кратность; возвращает вещественный массив
    в factor раз длиннее.

    Вся работа — в validate.interpolated_cut: восстановление точное, через
    (5-3), с центрированным номером бина, и проверено против прямой суммы
    по определению (см. её докстроку).
    """
    return np.abs(interpolated_cut(np.asarray(cut), factor))


def width_at(profile: np.ndarray, level_db: float, cells: float,
             factor: int = OVERSAMPLE) -> float:
    """Ширина отклика на заданном уровне, в ЭЛЕМЕНТАХ РАЗРЕШЕНИЯ.

    Принимает уплотнённый профиль, уровень в дБ (отрицательный), ширину
    элемента разрешения в отсчётах и кратность уплотнения; возвращает
    ширину.

    Считается по пересечениям уровня слева и справа от пика, с линейной
    доводкой между соседними точками уплотнённого профиля. В элементах
    разрешения, а не в отсчётах и не в метрах, потому что осмысленно
    сравнивать надо с единицей: у сфокусированной цели ширина по -3 дБ
    равна 0,886 элемента, и всякое «в полтора раза шире» видно сразу.

    ПИК НА КРАЮ СРЕЗА — отказ, возвращается NaN. Хвост с такой стороны
    обрезан, и ширина занизилась бы, а то и вышла нулём: цикл поиска
    пересечения не смог бы сделать ни шага. Первая версия этого не
    проверяла, и карта отношения азимут/дальность показывала 2e12 — деление
    на такой ноль.
    """
    peak = int(np.argmax(profile))
    if peak == 0 or peak == profile.size - 1:
        return float("nan")
    threshold = profile[peak] * 10.0 ** (level_db / 20.0)

    def crossing(direction: int) -> float:
        i = peak
        while 0 < i < profile.size - 1 and profile[i] > threshold:
            i += direction
        if profile[i] >= threshold:            # уровень не пересечён
            return float(abs(i - peak))
        a, b = profile[i - direction], profile[i]
        part = (a - threshold) / max(a - b, 1e-300)
        return float(abs(i - direction - peak) + part)

    return (crossing(-1) + crossing(+1)) / (cells * factor)


def islr(profile: np.ndarray, cells: float, factor: int = OVERSAMPLE) -> float:
    """Доля энергии ВНЕ главного лепестка, в децибелах.

    Принимает уплотнённый профиль, ширину элемента разрешения в отсчётах и
    кратность; возвращает 10 lg (энергия снаружи / энергия внутри).

    Главным лепестком считается +-MAINLOBE_CELLS элемента разрешения от
    пика: первый ноль синка стоит ровно там. Число тем выше, чем больше
    энергии ушло в хвосты, — это и есть размаз одним числом.
    """
    peak = int(np.argmax(profile))
    half = int(round(MAINLOBE_CELLS * cells * factor))
    power = profile.astype(np.float64) ** 2
    inside = power[max(peak - half, 0) : peak + half + 1].sum()
    return 10.0 * np.log10(max(power.sum() - inside, 1e-300) / max(inside, 1e-300))


def usable_cut(profile: np.ndarray, level_db: float = CUT_DYNAMIC_DB) -> bool:
    """Годится ли срез для замера ширины на уровне -level_db.

    Принимает уплотнённый профиль; возвращает True, если пик выше медианы
    среза на level_db. Иначе уровень тонет в фоне и ширина бессмысленна —
    см. CUT_DYNAMIC_DB, там разбор ошибки, которую это ловит.
    """
    med = float(np.median(profile))
    if med <= 0.0:
        return True
    return 20.0 * np.log10(float(profile.max()) / med) >= level_db


def measure_target(image: np.ndarray, m: int, n: int, cells: float,
                   window: int) -> dict:
    """Все числа по одной цели."""
    profile = upsample(azimuth_cut(image, m, n, window))
    # по дальности окно берём вчетверо уже: там цель занимает единицы
    # стробов, и тянуть хвост на сотню незачем
    across = upsample(range_cut(image, m, n, max(window // 4, 8)))
    peak = float(profile.max())
    return {
        "m": m, "n": n,
        "peak_db": 20.0 * np.log10(max(peak, 1e-300)),
        "width_3db": width_at(profile, -3.0, cells),
        "width_10db": width_at(profile, -10.0, cells),
        "width_20db": width_at(profile, -20.0, cells),
        "islr_db": islr(profile, cells),
        # по дальности — в ОТСЧЁТАХ: сколько стробов в элементе разрешения,
        # отсюда не видно (см. range_cut)
        "range_3db": width_at(across, -3.0, 1.0),
        "range_20db": width_at(across, -20.0, 1.0),
        "usable": usable_cut(profile) and usable_cut(across),
        "profile": profile,
    }


def measure(image: np.ndarray, cells: float, count: int = 8) -> list[dict]:
    """Таблица по картинке: count самых ярких одиночных целей."""
    window = int(round(WINDOW_CELLS * cells))
    return [measure_target(image, m, n, cells, window)
            for m, n in find_targets(image, cells, count, window)]


def smear_map(image: np.ndarray, cells: float, r_a: float, r_b: float,
              tiles_m: int = MAP_TILES_M, tiles_n: int = MAP_TILES_N):
    """КАРТА размаза: где картинка растянута по азимуту, а где нет.

    Принимает картинку, ширину элемента разрешения в отсчётах, разрешение по
    азимуту и шаг по дальности в метрах и разбиение; возвращает три массива
    (tiles_m, tiles_n): ISLR, ширина по -20 дБ в элементах и ОТНОШЕНИЕ
    ширины по азимуту к ширине по дальности, обе в метрах. NaN там, где
    годной цели не нашлось.

    ОТНОШЕНИЕ — главная из трёх карт, и вот почему. Расфокусировка
    растягивает отклик ТОЛЬКО по азимуту: по дальности автофокус не работает
    и фазовая ошибка туда не входит. Значит объект, широкий в обе стороны
    одинаково, — просто такого размера (куст, дерево, угол здания), и его
    ширина законна. А объект, вытянутый по азимуту в разы, размазан.

    Замер на записи владельца, по восьми ярким целям: медиана отношения была
    1,32 до автофокуса и стала 0,91 после — то есть там, где алгоритм
    отработал, азимутальный избыток снят целиком и осталась собственная
    ширина объектов. А цель в блоке, где алгоритм не работал, как имела
    отношение 2,22, так и осталась.

    Зачем. Таблица по восьми самым ярким целям отвечает на вопрос «каковы
    лучшие цели», а не «где картинка размазана». На записи владельца семь
    из восьми оказались в одном месте, и весь остальной кадр остался
    неизмеренным — а размаз он видел глазом именно там.

    В каждой плитке берётся её самый яркий пиксель. Если он не превышает
    медиану плитки на MAP_PEAK_OVER_MEDIAN_DB, цели в плитке нет (гладкое
    поле, вода) и в карту идёт NaN: мерить ширину отклика у спекла
    бессмысленно, ответ был бы случайным числом.
    """
    a = np.abs(np.asarray(image))
    M, N = a.shape
    window = int(round(WINDOW_CELLS * cells))
    edges_m = np.linspace(0, M, tiles_m + 1).astype(int)
    edges_n = np.linspace(0, N, tiles_n + 1).astype(int)
    islr_map = np.full((tiles_m, tiles_n), np.nan)
    width_map = np.full((tiles_m, tiles_n), np.nan)
    ratio_map = np.full((tiles_m, tiles_n), np.nan)

    for i in range(tiles_m):
        for j in range(tiles_n):
            tile = a[edges_m[i]:edges_m[i+1], edges_n[j]:edges_n[j+1]]
            if tile.size == 0:
                continue
            local = np.unravel_index(int(np.argmax(tile)), tile.shape)
            m = edges_m[i] + int(local[0])
            n = edges_n[j] + int(local[1])
            if not (window <= m < M - window):
                continue
            over = 20.0 * np.log10(max(tile.max(), 1e-300) /
                                   max(float(np.median(tile)), 1e-300))
            if over < MAP_PEAK_OVER_MEDIAN_DB:
                continue
            profile = upsample(azimuth_cut(image, m, n, window))
            across = upsample(range_cut(image, m, n, max(window // 4, 8)))
            # уровень -20 дБ обязан лежать ВЫШЕ фона среза, иначе меряется
            # не отклик цели, а спекл; см. CUT_DYNAMIC_DB
            if not (usable_cut(profile) and usable_cut(across)):
                continue
            islr_map[i, j] = islr(profile, cells)
            width_map[i, j] = width_at(profile, -20.0, cells)
            along_m = width_map[i, j] * r_a          # элементы разрешения -> метры
            across_m = width_at(across, -20.0, 1.0) * r_b   # отсчёты -> метры
            # ширина по дальности меньше половины отсчёта физически
            # невозможна: отклик не может быть уже сетки. Значит замер
            # негодный — пик у края среза или цель на границе кадра
            if across_m > 0.5 * r_b:
                ratio_map[i, j] = along_m / across_m
    return islr_map, width_map, ratio_map


def compare(before: np.ndarray, after: np.ndarray, cells: float,
            count: int = 8) -> list[dict]:
    """Та же таблица для двух картинок, по ОДНИМ И ТЕМ ЖЕ целям.

    Принимает две картинки, ширину элемента разрешения в отсчётах и число
    целей; возвращает список словарей с ключами 'before' и 'after'.

    Цели ищутся на картинке ДО и меряются в обеих на том же месте. Искать
    отдельно в каждой нельзя: тогда в сравнение попали бы разные цели, и
    таблица сказала бы что угодно.
    """
    window = int(round(WINDOW_CELLS * cells))
    rows = []
    for m, n in find_targets(before, cells, count, window):
        rows.append({
            "m": m, "n": n,
            "before": measure_target(before, m, n, cells, window),
            "after": measure_target(after, m, n, cells, window),
        })
    return rows
