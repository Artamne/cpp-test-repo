"""Этап B. Начальное приближение фазы. Формулы (4-83),(4-84),(5-27)…(5-30),
§4 документа.

Порядок функций — порядок выполнения:

    azimuth_frequency_axis                       ось f_a блока для (5-27)
    range_coefficients_at_scene_centre           k_10, k_20, k_30
    spatially_variant_quadratic_coefficients     (5-27),(5-28)  D_x, D_y
    phase_model                                  (5-27)  eps, вектор длины блока
    block_scale_factor                           (5-29)  eta, скаляр
    initial_phase                                (5-30)  phi^(0)

Выполняется ОДИН РАЗ на блок, до итераций.

Что этап B даёт и чего не даёт — §2.3 документа. Он описывает
детерминированную фазу штатного движения; неучтённые отклонения носителя в
него не входят по построению. На ровном полёте даст phi^(0) близкое к нулю
и сходимость будет медленнее — это не дефект, так и должно быть.
"""

from __future__ import annotations

import numpy as np

from stage_a_blocks import Geometry, motion_constants


def azimuth_frequency_axis(m_block: int, T_a: float, M_aperture: int) -> np.ndarray:
    """Ось азимутальных частот f_a для (5-27). Принимает число бинов блока
    m_block, время синтеза T_a и число импульсов в апертуре M_aperture;
    возвращает вектор длины m_block в герцах.

    Раскладка не выбрана произвольно, а следует из ядра (5-3): бину k
    соответствует частота numpy.fft.fftfreq(m_block, 1/PRF)[k].

    Длина и полоса — РАЗНЫЕ величины, и путать их нельзя. Длина берётся у
    блока: §5 документа говорит «далее M, N — размеры блока», то есть сумма
    (5-3) идёт по бинам блока, и вектор фазы имеет столько же отсчётов.
    Полоса берётся у радара: PRF = M_aperture / T_a по §1.3, где M_aperture —
    число импульсов в апертуре, одно на всю сцену. Блок не сужает полосу
    доплера, он лишь реже её опрашивает — его сетка накрывает ту же полосу
    с шагом PRF / m_block.
    """
    prf = M_aperture / T_a
    return np.fft.fftfreq(m_block, d=1.0 / prf)


def range_coefficients_at_scene_centre(geom: Geometry) -> tuple[float, float, float]:
    """k_10, k_20, k_30 — коэффициенты хода дальности для центра сцены
    (§1.3, «неизменчивая часть»); входят в (5-27) и (5-28).

    Принимает Geometry; возвращает (k_10, k_20, k_30).

    ВНИМАНИЕ (место чтения, README): книга пользуется k_10, k_20, k_30 в
    (5-27)/(5-28), но нигде их не выписывает. Они восстановлены из того же
    разложения хода дальности, производными которого являются (4-83)/(4-84):

        R(t_a) = sqrt(R_B0^2 + 2 A_1 t_a + A_2 t_a^2 + mu_3 t_a^3)
               = R_B0 + k_10 t_a + k_20 t_a^2 + k_30 t_a^3 + ...

        k_10 = A_1 / R_B0
        k_20 = A_2 / (2 R_B0) - A_1^2 / (2 R_B0^3)
        k_30 = mu_3 / (2 R_B0) - A_1 A_2 / (2 R_B0^3) + A_1^3 / (2 R_B0^5)

    Восстановление проверяемо: производная k_1 по x_p, взятая от этих формул,
    обязана дать напечатанное в (4-83) Delta k_1x. Проверка стоит в
    validate.py, опыт «линеаризация».

    При прямолинейном полёте (§2.2) A_1 = 0, A_2 = v^2, mu_3 = 0, то есть
    k_10 = k_30 = 0 и k_20 = v^2 / (2 R_B0).
    """
    A_1, A_2, mu_3 = motion_constants(geom)
    R = geom.R_B0
    k_10 = A_1 / R
    k_20 = A_2 / (2 * R) - A_1**2 / (2 * R**3)
    k_30 = mu_3 / (2 * R) - A_1 * A_2 / (2 * R**3) + A_1**3 / (2 * R**5)
    return k_10, k_20, k_30


def spatially_variant_quadratic_coefficients(
    geom: Geometry, coef: dict[str, float]
) -> tuple[float, float]:
    """(5-27) D_x и (5-28) D_y — коэффициенты пространственно-изменчивой
    квадратичной фазы.

    Принимает Geometry и шесть коэффициентов (4-83)/(4-84);
    возвращает (D_x, D_y).

        D_x = (pi c / 8 f_0) ( (3 k_10 Dk_3x + 3 k_30 Dk_1x)/k_20^3
                               - 9 k_10 k_30 Dk_2x / k_20^4
                               - 2 Dk_2x / k_20^2 )

    D_y — то же с индексом y (5-28).
    """
    k_10, k_20, k_30 = range_coefficients_at_scene_centre(geom)
    if k_20 == 0.0:
        raise ValueError(
            "k_20 = 0: ход дальности не имеет квадратичного члена, (5-27)/(5-28) "
            "делят на k_20 — этап B для такой геометрии не определён"
        )

    factor = np.pi * geom.c / (8.0 * geom.f_0)

    def _D(dk1: float, dk2: float, dk3: float) -> float:
        return factor * (
            (3 * k_10 * dk3 + 3 * k_30 * dk1) / k_20**3
            - 9 * k_10 * k_30 * dk2 / k_20**4
            - 2 * dk2 / k_20**2
        )

    D_x = _D(coef["k1x"], coef["k2x"], coef["k3x"])
    D_y = _D(coef["k1y"], coef["k2y"], coef["k3y"])
    return D_x, D_y


def phase_model(D_x: float, D_y: float, x_p: float, y_p: float, f_a: np.ndarray) -> np.ndarray:
    """(5-27): eps = (D_x x_p + D_y y_p) f_a^2 — модель пространственно-
    изменчивой квадратичной фазы.

    Принимает D_x, D_y, координаты точки (x_p, y_p) относительно центра сцены
    и ось частот f_a блока; возвращает вектор той же длины, индексируемый
    тем же k, что и phi_k.
    """
    return (D_x * x_p + D_y * y_p) * f_a**2


def block_scale_factor(
    D_x: float,
    D_y: float,
    x_centre: float,
    y_centre: float,
    x_max: float,
    y_max: float,
    q: int,
    q_k: int,
) -> float:
    """(5-29): масштабный множитель блока eta_qk — скаляр.

    Принимает D_x, D_y, центр блока (x_centre, y_centre), опорную точку
    (x_max, y_max) = полуразмеры блока из этапа A, общее число блоков q и
    номер блока q_k; возвращает eta.

        eta_qk = (D_x x_qk + D_y y_qk) / (D_x x_max + D_y y_max) - (q - q_k)/2

    В числителе — изменчивость в центре q_k-го блока относительно центра
    сцены, в знаменателе — максимальная изменчивость в блоке, содержащем
    центр сцены (§4.4). Множитель f_a^2 в отношении сокращается.

    Член -(q - q_k)/2 в книге НЕ ВЫВЕДЕН — см. §8 документа: при q = 6,
    q_k = 2 он даёт -2, а приведённый в книге пример eta = -0,39 требует,
    чтобы первое слагаемое было 1,61, то есть больше единицы при знаменателе,
    названном максимальным. Здесь реализована рабочая форма основного текста,
    то есть член оставлен.
    """
    denominator = D_x * x_max + D_y * y_max
    if denominator == 0.0:
        ratio = 0.0
    else:
        ratio = (D_x * x_centre + D_y * y_centre) / denominator
    # РАСХОЖДЕНИЕ (5-29): в книге напечатано иначе, см. §8 — член -(q - q_k)/2
    # не выведен и противоречит примеру книги. Оставлен как рабочая форма
    # основного текста; чего он стоит — замерено, см. validate.experiment_eta_term.
    return ratio - (q - q_k) / 2.0


def initial_phase(eta: float, eps: np.ndarray) -> np.ndarray:
    """(5-30): phi^(0)_qk = eta_qk * eps_qk — стартовый вектор для итераций
    этапа C в блоке q_k.

    Принимает скаляр eta (5-29) и вектор eps (5-27); возвращает вектор той же
    длины, что и eps, то есть по числу бинов блока.

    ВНИМАНИЕ (место чтения, README): о длине этого вектора книга говорит
    ДВАЖДЫ И ПО-РАЗНОМУ. §4.5 и блок-схема §7 называют его «вектор длины M»,
    где M — размер сцены; §5, открывая этап C, объявляет «далее M, N —
    размеры блока». Взято второе: (5-3) суммирует по k = 1…M с ядром
    e^{-j2 pi k m / M}, и эта M обязана быть длиной преобразования, то есть
    размером блока. В список §8 книги это расхождение не попало — оно
    седьмое.

    ВНИМАНИЕ (место чтения, README): eps здесь берётся в опорной точке
    (x_max, y_max) — той же, что стоит в знаменателе (5-29). Иначе множитель
    (D_x x + D_y y) вошёл бы дважды. При таком чтении, если отбросить
    неразъяснённый член -(q - q_k)/2, произведение eta * eps сводится ровно
    к модели фазы в центре блока: (D_x x_qk + D_y y_qk) f_a^2.
    """
    return eta * eps
